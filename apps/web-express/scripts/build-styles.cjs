// Preserve cascade order while avoiding the master stylesheet's import waterfall.
const fs=require('node:fs'),path=require('node:path');
const root=path.join(__dirname,'../public/css');
const source=fs.readFileSync(path.join(root,'styles.css'),'utf8');
const files=[...source.matchAll(/@import\s+url\(['"]\.\/modules\/([^?'"\)]+)/g)].map(match=>match[1]);
const boundary=files.indexOf('admin.css'),tail=files.indexOf('pages.css');
if(boundary<0 || tail<boundary)throw new Error('Stylesheet boundaries changed; update bundle order.');
const write=(name,modules)=>fs.writeFileSync(path.join(root,name),'/* Generated by scripts/build-styles.cjs. */\n'+modules.map(file=>fs.readFileSync(path.join(root,'modules',file),'utf8')).join('\n'));
write('base.bundle.css',files.slice(0,boundary));
write('enhancements.bundle.css',files.slice(tail));
write('profile.bundle.css',['profile.css']);write('staff.bundle.css',['admin.css']);
write('platform.bundle.css',['platform.css']);
